'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const http = require('node:http');
const express = require('express');
const cheerio = require('cheerio');
const puppeteer = require('puppeteer-core');
const { WebSocketServer } = require('ws');
const { createTaskMediaCollections } = require('../src/apps/server/modules/media/task-media-collections');

test('任务来源分类和加入通过真实 WebSocket 在控制端同步', async t => {
    if (!fs.existsSync('/usr/bin/chromium')) return t.skip('Chromium 不可用');
    const root = path.resolve(__dirname, '../src/apps/web-mediacenter/ui/public');
    const $ = cheerio.load(fs.readFileSync(path.join(root, 'upload.html'), 'utf8'));
    const app = express(); app.use(express.json());
    app.get('/', (req, res) => res.send(`<div class="media-library-container">${$('.media-library-container').first().html()}</div><script src="/media-library.js"></script>`));
    app.get('/media-library.js', (req, res) => res.sendFile(path.join(root, 'js/media-library.js')));
    app.post('/api/task-media-sources/:id/resolve-link', (req, res) => res.json({ items: [{ id: '1', title: `已打开 ${req.body.url}`, mediaType: 'collection', url: req.body.url }] }));
    const server = http.createServer(app); const wss = new WebSocketServer({ server });
    const saved = {};
    const service = createTaskMediaCollections({ config: { get: (key, fallback) => saved[key] ?? fallback, set: (key, value) => { saved[key] = value; return true; } }, broadcast: msg => { for (const ws of wss.clients) if (ws.readyState === 1) ws.send(JSON.stringify(msg)); } });
    wss.on('connection', ws => { ws.on('message', raw => service.handle(ws, JSON.parse(String(raw)))); ws.send(JSON.stringify(service.snapshot())); });
    await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
    const browser = await puppeteer.launch({ executablePath: '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] }); t.after(async () => { await browser.close(); for (const ws of wss.clients) ws.terminate(); wss.close(); server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); });
    const base = `http://127.0.0.1:${server.address().port}`;
    const setup = async () => {
        const page = await browser.newPage(); await page.goto(base);
        await page.evaluate(() => {
            window.toasts = []; window.showToast = (text, type) => window.toasts.push({ text, type });
            const ws = new WebSocket(`ws://${location.host}`);
            window.WebSocketManager = { ws };
            ws.onmessage = event => { const data = JSON.parse(event.data); if (data.type === 'taskMediaCollections') MediaLibrary.handleTaskMediaCollections(data); if (data.type === 'taskMediaAddResult') MediaLibrary.handleTaskMediaAddResult(data); };
            MediaLibrary.taskMediaSources = [{ id: 'hongguo', name: '红果短剧', libraryId: 'task-auto:hongguo', features: ['resolveLink'] }, { id: 'tomato', name: '番茄', libraryId: 'task-auto:tomato', features: ['resolveLink'] }];
            MediaLibrary.activeTab = 'task'; MediaLibrary.activeTaskSourceId = 'hongguo'; MediaLibrary.renderTabs();
            document.getElementById('taskSourceAddBtn').onclick = () => MediaLibrary.addTaskMediaLink();
        });
        await page.waitForFunction(() => WebSocketManager.ws.readyState === WebSocket.OPEN);
        return page;
    };
    const a = await setup(), b = await setup();
    await a.evaluate(() => { window.prompt = () => '短剧'; [...document.querySelectorAll('#taskMediaFolderNavigation button')].find(node => node.textContent.includes('新建')).click(); });
    await b.waitForFunction(() => document.querySelector('#taskMediaFolderNavigation').textContent.includes('短剧'), { timeout: 5000 });
    await a.evaluate(() => [...document.querySelectorAll('#taskMediaFolderNavigation button')].find(node => node.textContent.includes('短剧')).click());
    await a.evaluate(() => { document.getElementById('taskSourceLinkInput').value = 'https://hongguoduanju.com/player/123'; document.getElementById('taskSourceAddBtn').click(); });
    await a.waitForFunction(() => window.toasts.some(x => x.text === '已加入文件夹'));
    assert.equal(await a.evaluate(() => MediaLibrary.taskMediaShowingSaved), true);
    await b.evaluate(() => [...document.querySelectorAll('#taskMediaFolderNavigation button')].find(node => node.textContent.includes('短剧')).click());
    await b.waitForFunction(() => document.querySelector('#taskMediaSourceList').textContent.includes('player/123'), { timeout: 5000 });
    await b.select('#taskMediaSourceList select[aria-label="移动到文件夹"]', '');
    await a.waitForFunction(() => document.querySelector('#taskMediaSourceList').textContent.includes('暂无内容'), { timeout: 5000 });
    await b.evaluate(() => [...document.querySelectorAll('#taskMediaFolderNavigation button')].find(node => node.textContent.includes('未分类')).click());
    await b.waitForFunction(() => document.querySelector('#taskMediaSourceList').textContent.includes('player/123'), { timeout: 5000 });
    await b.evaluate(() => [...document.querySelectorAll('#taskMediaSourceList button')].find(node => node.textContent === '打开').click());
    await b.waitForFunction(() => document.querySelector('#taskMediaSourceList').textContent.includes('已打开'));
    await b.evaluate(() => { MediaLibrary.activeTaskSourceId = 'tomato'; MediaLibrary.taskMediaShowingSaved = false; MediaLibrary.renderTabs(); });
    assert.equal(await b.$eval('#taskMediaFolderNavigation', node => node.textContent.includes('短剧')), false);
    const c = await setup();
    await c.evaluate(() => [...document.querySelectorAll('#taskMediaFolderNavigation button')].find(node => node.textContent.includes('未分类')).click());
    await c.waitForFunction(() => document.querySelector('#taskMediaSourceList').textContent.includes('player/123'), { timeout: 5000 });
    await c.evaluate(() => [...document.querySelectorAll('#taskMediaSourceList button')].find(node => node.textContent === '移除').click());
    await c.waitForFunction(() => document.querySelector('#taskMediaSourceList').textContent.includes('暂无内容'), { timeout: 5000 });
    assert.equal(saved['media.taskMediaCollections'].hongguo.items.length, 0);
    await c.evaluate(() => { document.getElementById('taskSourceLinkInput').value = 'https://example.com/?token=secret'; document.getElementById('taskSourceAddBtn').click(); });
    await c.waitForFunction(() => window.toasts.some(x => x.type === 'error' && x.text.includes('不得包含凭据')));
    assert.equal(await c.evaluate(() => Boolean(MediaLibrary.pendingTaskMediaAdd)), false);
});
