assert.equal(restored.hits,6);assert.equal(restored.misses,0);
assert.notEqual(restored.groups[0],restored.groups[1]);
assert(restored.sharpEdges.includes('0:1'));
// 两张很接近的源面可以有不同朝向。只有同一位置的角法线确实分裂时，人物笼才应出现硬缝。
